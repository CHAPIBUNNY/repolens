export function renderSiteLlmsTxt({ origin, basePath, pages = [] }) {
  const lines = [renderLlmsTxt().trimEnd(), "", "## Gallery pages", ""];
  const sorted = [...pages].sort((a, b) => String(a.name).localeCompare(String(b.name)));
  for (const page of sorted) {
    const explained = pageUrl(origin, basePath, `${page.slug}/explained/`);
    const score = pageUrl(origin, basePath, `${page.slug}/score/`);
    const scoreText = page.stats?.health?.score == null ? "code health" : `code health ${page.stats.health.score}`;
    lines.push(`- [${page.name} architecture explained](${explained}): ${page.blurb}`);
    lines.push(`- [${page.name} ${scoreText}](${score}): shields.io badge for this scan`);
  }
  if (!sorted.length) {
    lines.push(`- [Gallery index](${pageUrl(origin, basePath, "")}): curated architecture pages`);
  }
  lines.push("");
  return lines.join("\n");
}

export function renderSiteLlmsFull({ origin, basePath, pages = [] }) {
  const site = renderSiteLlmsTxt({ origin, basePath, pages });
  const extra = site.split("## Gallery pages\n")[1] || "";
  return `${renderLlmsFull().trimEnd()}\n\n## Gallery pages\n${extra}`;
}
