function pageUrl(origin, basePath, rel) {
  const base = String(basePath || "").replace(/\/$/, "");
  const suffix = rel ? `/${String(rel).replace(/^\//, "")}` : "/";
  const joined = `${base}${suffix}`.replace(/\/{2,}/g, "/");
  return `${origin}${joined.startsWith("/") ? joined : `/${joined}`}`;
}

