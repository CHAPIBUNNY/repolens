export const ARCHITECTURE_COMMENT_MARKER = "<!-- repolens:architecture-diff -->";

export const REPO_URL = "https://github.com/CHAPIBUNNY/repolens";
export const GALLERY_URL = "https://chapibunny.github.io/repolens/";

export const COMMENT_FOOTER =
  `Generated by [RepoLens](${REPO_URL}) · [Gallery](${GALLERY_URL})`;

export function isArchitectureComment(body) {
  return typeof body === "string" && (
    body.includes(ARCHITECTURE_COMMENT_MARKER)
    || body.includes("## RepoLens — Architecture Summary")
    || body.includes("## RepoLens — Architecture diff")
  );
}
